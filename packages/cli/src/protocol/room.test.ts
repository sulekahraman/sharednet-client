import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { Room, contentHash, emptyProjection, evalPredicate, legal, pythonJson, replayStep, replayEvents } from "./room.ts";
import type { CanonicalEvent } from "./envelope.ts";

const dir = join(import.meta.dirname, "fixtures");
const read = (name: string) => JSON.parse(readFileSync(join(dir, name), "utf8"));
type Outcome = { accepted: boolean; code: string | null; binding: boolean; seq: number | null };
type Fixture = { name?: string; seed?: number; members: string[]; events: CanonicalEvent[]; outcomes: Outcome[]; digest: string };

const conformance = read("conformance.json") as { fixtures: Fixture[] };
const fuzz = read("fuzz.json") as { logs: Fixture[] };
const all: Fixture[] = [...conformance.fixtures, ...fuzz.logs];
const eventCount = all.reduce((n, f) => n + f.events.length, 0);

/**
 * The fixtures are generated by the reference implementation in the research repository and
 * carry, per event, the admission outcome it produced and, per scenario, the digest of the
 * projection it ended on. They are the oracle: a rule here that disagrees with them is wrong,
 * however reasonable it looks.
 */
describe(`the reference semantics, replayed over ${eventCount} generated events`, () => {
  it.each(conformance.fixtures.map((f) => [f.name!, f] as const))(
    "conformance: %s reproduces every outcome and the digest",
    (_name, fixture) => {
      const room = new Room(fixture.members);
      const got = fixture.events.map((event) => {
        const r = room.ingest(event);
        return { accepted: r.accepted, code: r.code, binding: r.binding, seq: r.seq };
      });
      expect(got).toEqual(fixture.outcomes);
      expect(room.digest()).toBe(fixture.digest);
    },
  );

  it(`fuzz: all ${fuzz.logs.length} logs reproduce every outcome and digest`, () => {
    const wrong: string[] = [];
    for (const log of fuzz.logs) {
      const room = new Room(log.members);
      const got = log.events.map((event) => {
        const r = room.ingest(event);
        return { accepted: r.accepted, code: r.code, binding: r.binding, seq: r.seq };
      });
      if (JSON.stringify(got) !== JSON.stringify(log.outcomes)) wrong.push(`seed ${log.seed}: outcomes`);
      if (room.digest() !== log.digest) wrong.push(`seed ${log.seed}: digest`);
    }
    expect(wrong).toEqual([]);
  });
});

/**
 * The digest is a hash of `json.dumps(projection, sort_keys=True)` as Python writes it. Three
 * details decide whether it matches, and all three differ from `JSON.stringify`: sorted keys,
 * a space after `:` and `,`, and escaped non-ASCII. Each is worth its own case, because getting
 * one wrong yields a digest that is stable, plausible, and wrong everywhere.
 */
describe("the digest is Python's serialisation, not JavaScript's", () => {
  it("sorts object keys", () => {
    expect(pythonJson({ b: 1, a: 2 })).toBe('{"a": 2, "b": 1}');
  });
  it("puts a space after the separators, where JSON.stringify puts none", () => {
    expect(pythonJson({ a: [1, 2] })).toBe('{"a": [1, 2]}');
    expect(JSON.stringify({ a: [1, 2] })).toBe('{"a":[1,2]}');
  });
  it("escapes non-ASCII", () => {
    expect(pythonJson({ task: "改登录页" })).toBe('{"task": "\\u6539\\u767b\\u5f55\\u9875"}');
  });
  it("hashes the first 24 hex characters, prefixed", () => {
    const expected = "sha256:" + createHash("sha256").update('{"clock": 0, "work": {}}').digest("hex").slice(0, 24);
    expect(contentHash(emptyProjection())).toBe(expected);
  });
});

describe("admission refuses before it reaches the lifecycle table", () => {
  const base = conformance.fixtures[0]!.events[0]!;
  const room = () => new Room(["A", "B", "C", "D", "E"]);

  it("refuses an actor who is not a member", () => {
    expect(room().admit({ ...base, actor: "Z" }).code).toBe("NOT_MEMBER");
  });
  it("refuses another protocol, which is how UNSUPPORTED_PROTOCOL is reachable at all", () => {
    expect(room().admit({ ...base, version: "sha256:protocol-v2" }).code).toBe("UNSUPPORTED_PROTOCOL");
  });
  it("refuses a clause kind it does not know, without looking at the work item", () => {
    expect(room().admit({ ...base, clauses: [{ kind: "priority", level: "high" }] }).code).toBe("UNKNOWN_TYPED_CLAUSE");
  });
  it("refuses a parent hash no accepted event has", () => {
    expect(room().admit({ ...base, parents: ["sha256:nothing"] }).code).toBe("MISSING_PARENT");
  });
  it("lets the room service tick the clock although it is not a member", () => {
    const tick = { ...base, type: "clock.tick", actor: "room_service", work_id: null, to: [], payload: { t: 1 } };
    expect(room().admit(tick).accepted).toBe(true);
  });
  it("accepts a message without consulting the lifecycle at all", () => {
    const message = { ...base, type: "message", work_id: null, to: [], payload: { text: "hi" } };
    expect(room().admit(message).accepted).toBe(true);
  });
});

describe("an idempotency key replays rather than reapplying", () => {
  it("returns the original seq, marks it DUPLICATE, and leaves the projection alone", () => {
    const room = new Room(["A", "B"]);
    const request = {
      type: "work.request", actor: "A", work_id: "W1", to: ["B"], payload: {}, refs: {},
      clauses: [], parents: [], idempotency_key: "k1",
    } as CanonicalEvent;
    const first = room.ingest(request);
    const digestAfterFirst = room.digest();
    const second = room.ingest(request);

    expect(first.accepted).toBe(true);
    expect(second).toMatchObject({ accepted: true, code: "DUPLICATE", seq: first.seq, binding: false });
    expect(room.log).toHaveLength(1);
    expect(room.digest()).toBe(digestAfterFirst);
  });
});

describe("the fold and the preconditions are separate concerns", () => {
  const request = {
    type: "work.request", actor: "A", work_id: "W1", to: ["B"], payload: {}, refs: {},
    clauses: [], parents: [], idempotency_key: null,
  } as CanonicalEvent;

  it("legal reads the projection and does not change it", () => {
    const projection = replayStep(emptyProjection(), request);
    const before = contentHash(projection);
    legal(projection, { ...request, type: "work.accept", actor: "B" });
    expect(contentHash(projection)).toBe(before);
  });

  it("replayStep returns a new projection rather than mutating the one it is given", () => {
    const projection = emptyProjection();
    const next = replayStep(projection, request);
    expect(projection.work).toEqual({});
    expect(next.work.W1!.state).toBe("OPEN");
  });

  it("evaluates a closed predicate language over the projection", () => {
    let projection = replayStep(emptyProjection(), request);
    expect(evalPredicate(projection, { op: "resolved", work: "W1" })).toBe(false);
    expect(evalPredicate(projection, { op: "clock_ge", t: 0 })).toBe(true);
    projection = replayStep(projection, { ...request, type: "work.accept", actor: "B" });
    expect(projection.work.W1!.state).toBe("COMMITTED");
    expect(projection.work.W1!.responsible).toBe("B");
  });
});

describe("production admission and durable replay", () => {
  const request: CanonicalEvent = {
    type: "work.request", actor: "A", work_id: "W1", to: ["B"], payload: {}, refs: {},
    clauses: [], parents: [], idempotency_key: "same-key",
  };

  it("escapes supplementary Unicode as Python surrogate pairs and sorts keys by code point", () => {
    expect(pythonJson({ "😀": "😀", "\ue000": 1 })).toBe('{"\\ue000": 1, "\\ud83d\\ude00": "\\ud83d\\ude00"}');
  });

  it("authenticates before an idempotent retry", () => {
    const room = new Room(["A", "B"]);
    room.ingest(request);
    room.members.delete("A");
    expect(room.ingest(request).code).toBe("NOT_MEMBER");
  });

  it("scopes retries to actor and conflicts when that actor changes the body", () => {
    const room = new Room(["A", "B"]);
    room.ingest(request);
    expect(room.ingest({ ...request, actor: "B", work_id: "W2" })).toMatchObject({ accepted: true, seq: 2, code: null });
    expect(room.ingest({ ...request, payload: { task: "changed" } })).toMatchObject({ accepted: false, code: "IDEMPOTENCY_CONFLICT" });
    expect(room.log).toHaveLength(2);
  });

  it.each(["__proto__", "constructor", "toString"])("treats %s as an ordinary own work and requirement key", (key) => {
    const room = new Room(["A", "B"]);
    expect(room.ingest({ ...request, work_id: key, clauses: [{ kind: "verify", id: key, verifier: "A" }] }).accepted).toBe(true);
    expect(Object.hasOwn(room.projection.work, key)).toBe(true);
    expect(Object.hasOwn(room.projection.work[key]!.requirements, key)).toBe(true);
    expect(room.ingest({ ...request, type: "work.accept", actor: "B", work_id: key, idempotency_key: null }).accepted).toBe(true);
  });

  it("refuses phantom work and deliverables inherited from Object.prototype", () => {
    const room = new Room(["A", "B"]);
    expect(evalPredicate(room.projection, { op: "hasResult", work: "constructor" })).toBe(false);
    expect(room.ingest({ ...request, clauses: [{ kind: "resolve_if", predicate: { op: "resolved", work: "constructor" } }] }).code).toBe("BAD_PREDICATE");
    room.ingest({ ...request, clauses: [{ kind: "deliverables", names: ["constructor"] }] });
    room.ingest({ ...request, type: "work.accept", actor: "B", idempotency_key: null });
    expect(room.ingest({ ...request, type: "work.result", actor: "B", idempotency_key: null }).code).toBe("MISSING_EVIDENCE");
  });

  it("owns the admitted data so later caller mutation cannot rewrite history", () => {
    const room = new Room(["A", "B"]);
    const event = structuredClone(request);
    room.ingest(event);
    event.payload.task = "rewritten";
    expect(room.log[0]!.payload).toEqual({});
  });

  it("restores parents, retries and projection after a historical actor leaves", () => {
    const room = new Room(["A", "B"]);
    room.ingest(request);
    const accepted = { ...request, type: "work.accept", actor: "B", idempotency_key: "accept", parents: [room.log[0]!.hash] };
    room.ingest(accepted);
    const restored = Room.restore(["B"], room.log);
    expect(restored.digest()).toBe(room.digest());
    expect(replayEvents(room.log)).toEqual(room.projection);
    expect(restored.ingest(accepted)).toMatchObject({ code: "DUPLICATE", seq: 2 });
    expect(restored.ingest({ ...accepted, type: "work.result", idempotency_key: "result", parents: [room.log[1]!.hash] })).toMatchObject({ accepted: true, seq: 3 });
    expect(restored.projection.work.W1!.state).toBe("REVIEW");
  });

  it("refuses corrupt persisted sequence or content instead of silently rebuilding different history", () => {
    const room = new Room(["A", "B"]);
    room.ingest(request);
    expect(() => replayEvents([{ ...room.log[0]!, seq: 2 }])).toThrow(/sequence/);
    expect(() => replayEvents([{ ...room.log[0]!, payload: { task: "tampered" } }])).toThrow(/hash/);
  });

  it.each([null, {}, { ...request, clauses: [null] }, { ...request, to: 1 }, { ...request, clauses: [{ kind: "deliverables" }] }])("rejects malformed canonical events without throwing (%j)", (event) => {
    expect(new Room(["A", "B"]).ingest(event as CanonicalEvent)).toMatchObject({ accepted: false, code: "INVALID_EVENT" });
  });
});

describe("malformed predicates fail closed", () => {
  const request: CanonicalEvent = { type: "work.request", actor: "A", work_id: "W1", to: ["B"], payload: {}, refs: {}, clauses: [], parents: [], idempotency_key: null };
  it.each([7, "bad", { op: "and", args: 7 }, { op: "and", args: [null] }, { op: "clock_ge", t: "soon" }, { op: "satisfied", work: "W1" }])("rejects malformed predicate %j", (predicate) => {
    expect(new Room(["A", "B"]).ingest({ ...request, clauses: [{ kind: "resolve_if", predicate }] })).toMatchObject({ accepted: false, code: "BAD_PREDICATE" });
  });
});

it("escapes DEL consistently with Python ensure_ascii", () => {
  expect(pythonJson("\x7f")).toBe('"\\u007f"');
});

it("rehydrates every admitted fixture log to its original digest", () => {
  for (const fixture of all) {
    const original = new Room(fixture.members);
    for (const event of fixture.events) original.ingest(event);
    expect(contentHash(replayEvents(original.log))).toBe(fixture.digest);
    expect(Room.restore([], original.log).digest()).toBe(fixture.digest);
  }
});

it("refuses reference values that cannot name work or requirements", () => {
  const request: CanonicalEvent = { type: "work.request", actor: "A", work_id: "W1", to: ["B"], payload: {}, refs: { supersedes: { toString: null } }, clauses: [], parents: [], idempotency_key: null };
  expect(new Room(["A", "B"]).ingest(request)).toMatchObject({ accepted: false, code: "INVALID_EVENT" });
});
